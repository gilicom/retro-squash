/**
 * @param {string} key
 * @param {'en'|'he'} lang
 * @param {Record<string,string|number>} [vars]
 */
export function t(key, lang, vars) {
  let s = (STRINGS[lang] && STRINGS[lang][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
